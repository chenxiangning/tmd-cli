/**
 * RPC 幕布正文清洗 —— 剥 omp 上下文标签(2026-11-06 用户实证)。
 * omp 的 §数字§ 上下文标记会泄漏进模型输出,且常粘在栅栏开场同行
 * (`§20§ ```sql`):md 栅栏须行首才算开栅,标签不剥则整段 SQL 裸文直排
 * (guanjia 会话转录实证,围栏与正文全部原样上屏)。渲染前剥除使栅栏
 * 回到行首按 md 正常渲染;数据层不动(转录保真),仅 RPC 幕布呈现层消费。
 */

/** 剥 §数字§ 标记(连续标签逐个剥;至多带走一侧一个相邻空格,换行边界零改动)。
 * 优先吃尾随空格(「§20§ ```sql」→ 栅栏行首),尾随无空格则吃前导空格
 * (「见 §17§,」→「见,」不留悬空空格)。 */
export function stripCtxTags(text: string): string {
  return text.replace(/§\d+§ ?| §\d+§/g, "");
}
